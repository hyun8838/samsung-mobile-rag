def external_notice(route: str, ext: Optional[dict], cited: list) -> Optional[Tuple[str, str]]:
    """(수준, 문구) 또는 None. final_text에 이미 있는 머리말·출처는 반복하지 않고, 모순되는 경고만 분기한다."""
    if route == "insufficient":
        return ("info", "사용설명서 근거가 충분하지 않다고 판단했습니다.")
    if route != "external":
        return None
    ext = ext or {}
    if ext.get("accepted"):
        return ("caption", "답변 경로: 매뉴얼 밖 정보(삼성 공식 웹사이트 검색)")
    rejected = bool(ext.get("urls_rejected"))
    why = ("외부 검색 결과에 공식 도메인 밖 출처가 섞여 있어 그 답변을 폐기했습니다" if rejected
           else "외부 검색에서 공식 출처를 찾지 못해 그 답변을 사용하지 않았습니다")
    if cited:
        return ("warning", f"사용설명서에서 확인된 부분 답만 표시합니다. {why}.")
    return ("warning", f"사용설명서에서 근거를 찾지 못했고, {why}.")


def md(text: str) -> str:
    """st.markdown용: $ 이스케이프, 단일 줄바꿈 유지."""
    return text.replace("$", "\\$").replace("\n", "  \n")
